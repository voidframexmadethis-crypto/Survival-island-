export interface EngineAudioConfig {
  profileId: EngineSoundProfileId;
  idleHz: number;
  maxHz: number;
  redlineRpm: number;
  harmonicRatio: number; // second cylinder bank harmonic ratio
  subHarmonicMix: number;
  primaryWave: OscillatorType;
  secondaryWave: OscillatorType;
  exhaustCutoffMin: number;
  exhaustCutoffMax: number;
  lopeHz: number;
  lopeDepth: number;
  forcedInduction: 'none' | 'supercharger' | 'twin_turbo' | 'quad_turbo' | 'hybrid_e' | 'steam_chug' | 'rotor_prop';
  forcedInductionGain: number;
  gearCount: number;
  shiftPopGain: number;
  /** Extra low-shelf dB on the engine/exhaust bus. */
  lowEndBoostDb?: number;
}

export interface VehicleHandlingConfig {
  topLandSpeedMs: number;
  accelRate: number;
  brakeRate: number;
  coastDrag: number;
  reverseRatio: number;
  steerMaxRad: number;
  steerTurnRate: number;
  highSpeedSteerFactor: number; // 0..1 stability at Vmax
  pitchSquat: number; // nose lift under acceleration (rad)
  pitchDive: number; // nose dip under heavy braking (rad)
  rollGain: number; // lateral cornering body roll (rad)
  suspensionStiffness: number;
  suspensionDamping: number;
  aeroDownforceGrip: number; // 1.0 baseline -> 1.6 extreme track cars
}

