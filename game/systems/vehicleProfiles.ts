export function resolveVehicleArchetype(rawNameOrId: string): VehicleVisualArchetype {
  const s = rawNameOrId.toLowerCase();
  if (s.includes('tahoe') || s.includes('subwoofer') || s.includes('savage life') || s.includes('chevy_2000_sub')) {
    return 'chevy_tahoe';
  }
  if (s.includes('cadillac') || s.includes('deville') || s.includes('caddy')) {
    return 'cadillac';
  }
  if (s.includes('speedtail')) return 'mclaren_speedtail';
  if (s.includes('p1')) return 'mclaren_p1_gtr';
  if (s.includes('720s') || s.includes('lbw') || s.includes('lb-works') || s.includes('liberty walk')) {
    return 'mclaren_720s';
  }
  if (s.includes('valkyrie')) return 'aston_valkyrie';
  if (s.includes('vantage') || s.includes('aston')) return 'aston_vantage_gt3';
  if (s.includes('huracan') || s.includes('evo2')) return 'huracan_gt3';
  if (s.includes('monza') || s.includes('sp2')) return 'ferrari_monza_sp2';
  if (s.includes('sf90') || s.includes('stradale') || s.includes('ferrari')) return 'ferrari_sf90';
  if (s.includes('sls') || s.includes('amg') || s.includes('gullwing')) return 'sls_amg_black';
  if (s.includes('divo')) return 'bugatti_divo';
  if (s.includes('chiron') || s.includes('bugatti')) return 'bugatti_chiron';
  if (s.includes('sian') || s.includes('fkp') || s.includes('lamborghini')) return 'lamborghini_sian';
  if (s.includes('pagani') || s.includes('huayra')) return 'pagani_huayra';
  if (s.includes('koenigsegg') || s.includes('gemera')) return 'koenigsegg_gemera';
  if (s.includes('delage') || s.includes('d12')) return 'delage_d12';
  if (s.includes('mclaren') || s.includes('supercar')) return 'mclaren';
  if (s.includes('donk') || s.includes('el camino') || s.includes('el_camino')) return 'donk';
  if (s.includes('slab') || s.includes('mini truck') || s.includes('mini_truck')) return 'slab';
  if (s.includes('town car') || s.includes('town_car') || s.includes('lincoln')) return 'lowrider';
  if (s.includes('van') || s.includes('bubble van')) return 'chevy_tahoe';
  if (s.includes('lowrider') || s.includes('impala')) return 'lowrider';
  return 'generic_car';
}

export function resolveVehicleProfile(
  vehicleOrQuery:
    | string
    | Pick<ModularVehicleData, 'id' | 'name' | 'preset' | 'carId'>,
): VehicleProfile {
  if (typeof vehicleOrQuery === 'string') {
    if (VEHICLE_PROFILES[vehicleOrQuery]) return VEHICLE_PROFILES[vehicleOrQuery];
    const arch = resolveVehicleArchetype(vehicleOrQuery);
    const byArch = Object.values(VEHICLE_PROFILES).find((p) => p.archetype === arch);
    return byArch ?? VEHICLE_PROFILES.sports_car;
  }

  if (vehicleOrQuery.carId && VEHICLE_PROFILES[vehicleOrQuery.carId]) {
    return VEHICLE_PROFILES[vehicleOrQuery.carId];
  }

  // Match exotic_lift_<carId>_<ts> or direct id
  for (const key of Object.keys(VEHICLE_PROFILES)) {
    if (vehicleOrQuery.id === key || vehicleOrQuery.id.startsWith(`exotic_lift_${key}_`)) {
      return VEHICLE_PROFILES[key];
    }
  }

  const combined = `${vehicleOrQuery.carId ?? ''} ${vehicleOrQuery.name ?? ''} ${vehicleOrQuery.preset ?? ''}`;
  const arch = resolveVehicleArchetype(combined);
  if (arch !== 'generic_car') {
    const byArch = Object.values(VEHICLE_PROFILES).find((p) => p.archetype === arch);
    if (byArch) return byArch;
  }

  if (vehicleOrQuery.preset && VEHICLE_PROFILES[vehicleOrQuery.preset]) {
    return VEHICLE_PROFILES[vehicleOrQuery.preset];
  }

  return VEHICLE_PROFILES.expedition_rover;
}
