export const DEFAULT_MANUFACTURER_ID = 'independent-build';
export const DEFAULT_COASTER_TYPE_ID: CoasterTypeId = 'steel_sit_down';

export function getManufacturer(id: string): ManufacturerProfile | null {
  return MANUFACTURERS.find((manufacturer) => manufacturer.id === id) ?? null;
}

export function getCoasterType(id: string): CoasterTypeProfile | null {
  return COASTER_TYPES.find((type) => type.id === id) ?? null;
}

export function manufacturersByCategory(category: ManufacturerCategory): ManufacturerProfile[] {
  return MANUFACTURERS.filter((manufacturer) => manufacturer.category === category);
}

export function searchManufacturers(query: string): ManufacturerProfile[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return MANUFACTURERS;
  return MANUFACTURERS.filter((manufacturer) =>
    [
      manufacturer.name,
      manufacturer.country,
      manufacturer.specialization,
      ...manufacturer.coasterCategories,
      ...manufacturer.documentedExamples,
    ]
      .join(' ')
      .toLowerCase()
      .includes(needle),
  );
}

export function manufacturerSupportsType(
  manufacturer: ManufacturerProfile,
  typeId: CoasterTypeId,
): boolean {
  return manufacturer.compatibleTypes.includes(typeId);
}

export function manufacturerSupportsElement(
  manufacturer: ManufacturerProfile,
  element: CoasterElementKind,
): boolean {
  return manufacturer.compatibleElements.includes(element);
}

export function defaultTrainForType(typeId: CoasterTypeId): {
  bodyStyle: TrainBodyStyle;
  restraint: RestraintKind;
  wheels: WheelStyle;
  cars: number;
  rowsPerCar: number;
  seatsPerRow: number;
} {
  const type = getCoasterType(typeId) ?? getCoasterType(DEFAULT_COASTER_TYPE_ID)!;
  return {
    bodyStyle: type.defaultBodyStyle,
    restraint: type.defaultRestraint,
    wheels: type.defaultWheels,
    cars: type.defaultCars,
    rowsPerCar: type.defaultRows,
    seatsPerRow: type.defaultSeats,
  };
}

