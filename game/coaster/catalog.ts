export type ManufacturerCategory = 'united_states' | 'china' | 'international';
export type ManufacturerStatus = 'active' | 'historical' | 'unverified';
export type ManufacturerClassification =
  | 'established'
  | 'independent'
  | 'lower_cost'
  | 'similar_designs'
  | 'historical'
  | 'unverified';

export interface ManufacturerProfile {
  id: string;
  name: string;
  country: string;
  category: ManufacturerCategory;
  status: ManufacturerStatus;
  classification: ManufacturerClassification;
  founded?: string;
  successor?: string;
  specialization: string;
  coasterCategories: string[];
  trackCharacteristics: string;
  trainCharacteristics: string;
  restraints: RestraintKind[];
  wheelConfigurations: WheelStyle[];
  materials: string[];
  compatibleTypes: CoasterTypeId[];
  compatibleElements: CoasterElementKind[];
  documentedExamples: string[];
  notes?: string;
}

export interface CoasterTypeProfile {
  id: CoasterTypeId;
  label: string;
  group: string;
  detail: string;
  trackStyle: 'steel' | 'wood' | 'hybrid' | 'single_rail' | 'water' | 'alpine';
  supportMaterial: SupportMaterial;
  defaultBodyStyle: TrainBodyStyle;
  defaultRestraint: RestraintKind;
  defaultWheels: WheelStyle;
  defaultCars: number;
  defaultRows: number;
  defaultSeats: number;
  compatibleElements: CoasterElementKind[];
}

